// A tiny seeded random source (mulberry32) so screenshot scenes and any
// fixed-seed game are perfectly repeatable, while normal play can seed it
// from the clock.

export function createRandom(seed) {
  let a = seed >>> 0;
  return function nextRandom() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
